// Writes the generated parts of the project page: site/games/<game>.html (one rules page per
// game, carrying its spec verbatim). Run it with `pnpm site:gen`; `pnpm site` runs it first.
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { join, resolve } from 'node:path'

const root = resolve(import.meta.dirname, '../..')
const REPO = 'https://github.com/jerzakm/ecs-arena'


const GAMES = [
  {
    id: 'rts', name: 'RTS', spec: 'SPEC.md', shot: 'rts-war', watch: '../viewer/?scenario=war&impl=koota',
    summary: 'Two armies fight over 7 shrines. Squads spawn in waves, warlords lead warbands, squads rout and flee, units carry items and buffs and keep a threat list, and garrisons hold shrines. It measures throughput on a large world with deep relations.',
    scenarios: [['skirmish', 'about 5k peak entities, 1000 ticks', 'board'], ['war', 'about 50k entities, 1000 ticks', 'board'], ['skirmish-smoke', '', 'smoke'], ['war-smoke', '', 'smoke'], ['battle', '', 'other']],
  },
  {
    id: 'survivors', name: 'Survivors', spec: 'SPEC-survivors.md', shot: 'survivors-swarm', watch: '../viewer/?scenario=swarm&impl=koota',
    summary: 'One player against waves of mobs, with weapons, projectiles, particles, pickups, status effects and level-ups. It measures the fixed cost of 36 small systems, heavy churn and short-lived tags on a small world.',
    scenarios: [['grove', 'about 1.1k live entities', 'board'], ['swarm', 'about 3k live entities', 'board'], ['grove-smoke', '', 'smoke'], ['swarm-smoke', '', 'smoke'], ['thicket', '', 'other']],
  },
  {
    id: 'factory', name: 'Factory', spec: 'SPEC-factory.md', shot: 'factory-mill', watch: '../viewer/factory.html?scenario=mill&impl=bitecs',
    summary: 'A grid of districts full of machines that turn ore into plates and gears. Drones fly production-line routes with stacks of crates, shift changes swap drones in bulk, and power outages switch whole districts off. works measures queries and change detection on a large, mostly idle world; mill measures dense iteration and heavy Working tag churn. Both measure transform propagation.',
    scenarios: [['mill', '1.6k machines, about 75% working', 'board'], ['works', '150k machines, about 1.5% working', 'board'], ['mill-smoke', '', 'smoke'], ['works-smoke', '', 'smoke']],
  },
]

// The "What the large games test" table of docs/features.md, one column per game.
const readme = await readFile(join(root, 'docs/features.md'), 'utf8')
const facetRows = readme.split('## What the large games test')[1].split('\n## ')[0].split('\n').filter((l) => l.startsWith('| ')).slice(1)
  .map((l) => l.split('|').slice(1, -1).map((c) => c.trim()))
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
const code = (s) => esc(s).replace(/`([^`]+)`/g, '<code>$1</code>')

const page = (g, i, spec) => `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${g.name} rules · ECS Arena</title>
<meta name="description" content="The rules of the ${g.name} game in ECS Arena, generated from ${g.spec}.">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link href="https://fonts.googleapis.com/css2?family=JetBrains+Mono:wght@400;700&display=swap" rel="stylesheet">
<link rel="stylesheet" href="../style.css">
<script>try { const t = localStorage.getItem('theme'); if (t) document.documentElement.dataset.theme = t } catch {}</script>
</head>
<body>
<main>
<!-- Generated by runner/src/site-build.mjs from packages/spec/${g.spec}. Do not edit. -->
<nav class="top"><a href="../" class="small-logo">ECS ARENA</a> <span class="dim">/ games /</span> ${g.name.toLowerCase()}</nav>
<h1>${g.name}: the rules</h1>
<p>${code(g.summary)}</p>
<p class="meta">This page is generated from <a href="${REPO}/blob/main/packages/spec/${g.spec}">${g.spec}</a>. The file wins on any difference.</p>
<figure class="hero"><a href="${g.watch}"><img src="../shots/${g.shot}.webp" width="640" height="360" alt="${g.name} in the viewer after 300 ticks"></a><figcaption class="meta"><a href="${g.watch}">watch it in your browser →</a></figcaption></figure>
<h2>Scenarios</h2>
<table><thead><tr><th>scenario</th><th>size</th><th>set</th></tr></thead><tbody>
${g.scenarios.map(([n, size, set]) => `<tr><td><code>${n}</code></td><td>${size}</td><td class="dim">${set}</td></tr>`).join('\n')}
</tbody></table>
<p class="meta">Board scenarios count toward the score. Smoke scenarios are short and run in CI.</p>
<h2>What it tests</h2>
<table><thead><tr><th>ECS feature</th><th>in ${g.name}</th></tr></thead><tbody>
${facetRows.filter((r) => r[i + 1]).map((r) => `<tr><td>${code(r[0])}</td><td>${code(r[i + 1])}</td></tr>`).join('\n')}
</tbody></table>
<h2>The spec</h2>
<article id="spec" class="spec"><p class="dim">Loading the spec. Without JavaScript, read <a href="${REPO}/blob/main/packages/spec/${g.spec}">${g.spec}</a> on GitHub.</p></article>
<footer class="meta"><a href="../">← ECS Arena</a> · <a href="${REPO}">GitHub</a> · MIT</footer>
</main>
<script type="text/markdown" id="spec-md">
${spec}
</script>
<script src="https://cdnjs.cloudflare.com/ajax/libs/marked/12.0.2/marked.min.js"></script>
<script>
const box = document.getElementById('spec')
box.innerHTML = marked.parse(document.getElementById('spec-md').textContent)
const base = '${REPO}/blob/main/packages/spec/'
for (const a of box.querySelectorAll('a[href]')) {
  const h = a.getAttribute('href')
  if (!/^(https?:|#|mailto:)/.test(h)) a.href = new URL(h, base).href
}
const used = new Set()
for (const h of box.querySelectorAll('h1, h2, h3, h4')) {
  let id = h.textContent.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
  while (used.has(id)) id += '-'
  used.add(id)
  h.id = id
  const a = document.createElement('a')
  a.href = '#' + id
  a.className = 'anchor'
  a.textContent = '#'
  h.append(' ', a)
}
if (location.hash) document.getElementById(location.hash.slice(1))?.scrollIntoView()
</script>
</body>
</html>
`

await mkdir(join(root, 'site/games'), { recursive: true })
for (const [i, g] of GAMES.entries()) {
  const spec = await readFile(join(root, 'packages/spec', g.spec), 'utf8')
  if (/<\/script/i.test(spec)) throw new Error(`${g.spec} contains </script, which would end the embedded block`)
  await writeFile(join(root, `site/games/${g.id}.html`), page(g, i, spec))
}
console.log('wrote site/games/{rts,survivors,factory}.html')
